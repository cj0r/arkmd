#!/usr/bin/env python3
"""Write design/theme-sheet.html: every theme's colours with hex values and sources, for checking against the
official repos, websites and VS Code extensions.   python3 tools/theme_sheet.py"""
import html, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
themes = json.load(open(os.path.join(ROOT, "shared", "web", "themes.json")))
GROUPS = [("Base", ["bg", "bgAlt", "surface", "selection", "fg", "fgMuted", "accent", "link"]),
          ("Headings", ["h1", "h2", "h3", "h4", "h5", "h6"]),
          ("Markdown", ["bold", "italic", "codeFg", "quoteBorder", "checkbox", "tag"]),
          ("Callouts", ["red", "orange", "yellow", "green", "cyan", "purple"])]


def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= .03928 else ((x + .055) / 1.055) ** 2.4 for x in c]
    return .2126 * c[0] + .7152 * c[1] + .0722 * c[2]


def contrast(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + .05) / (lb + .05)


def chip(label, value, bg, aa=None):
    ratio = "" if label in ("bg", "bgAlt", "surface", "selection") else f"<em>{contrast(value, bg):.1f}:1</em>"
    adj = (f'<span class="aa" title="WCAG AA adjustment">→ <span class="sw" style="background:{aa}"></span>'
           f'<code>{aa}</code> {contrast(aa, bg):.1f}:1</span>') if aa else ""
    return (f'<div class="chip"><span class="sw" style="background:{value}"></span>'
            f'<b>{label}</b><code>{value}</code>{ratio}{adj}</div>')


cards = []
for key, t in themes.items():
    aa = t.get("aa", {})
    rows = "".join(f'<h4>{g}</h4><div class="grid">{"".join(chip(k, t[k], t["bg"], aa.get(k)) for k in ks)}</div>' for g, ks in GROUPS)
    rows += '<h4>Syntax (reader code blocks)</h4><div class="grid">' + "".join(chip(k, v, t["bgAlt"], aa.get("hljs", {}).get(k)) for k, v in t["hljs"].items()) + "</div>"
    preview = (f'<div class="pv" style="background:{t["bg"]};color:{t["fg"]}">'
               + "".join(f'<div style="color:{t[f"h{n}"]};font-weight:700;font-size:{1.5 - n * .09:.2f}em">Heading {n}</div>' for n in range(1, 7))
               + f'<p>Text with <b style="color:{t["bold"]}">bold</b>, <i style="color:{t["italic"]}">italic</i>, '
               f'<code style="color:{t["codeFg"]};background:{t["bgAlt"]}">code</code> and <u style="color:{t["link"]}">link</u>.</p>'
               f'<pre style="background:{t["bgAlt"]}"><span style="color:{t["hljs"]["keyword"]}">def</span> '
               f'<span style="color:{t["hljs"]["function"]}">greet</span>(name): '
               f'<span style="color:{t["hljs"]["comment"]};font-style:italic"># hi</span>\n    '
               f'<span style="color:{t["hljs"]["keyword"]}">return</span> <span style="color:{t["hljs"]["string"]}">"hi "</span> + '
               f'<span style="color:{t["hljs"]["number"]}">42</span></pre></div>')
    cards.append(f'<section><h2>{html.escape(t["name"])} <small>{"dark" if t["dark"] else "light"} · {key}</small></h2>'
                 f'<p class="src">Source: {html.escape(t.get("source", ""))}</p><div class="cols">{preview}<div>{rows}</div></div></section>')

page = f"""<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>ArkMD theme sheet</title><style>
body{{font:14px/1.5 system-ui,sans-serif;margin:0;padding:16px;background:#f4f4f5;color:#18181b}}
section{{background:#fff;border:1px solid #ddd;border-radius:10px;padding:14px 18px;margin:0 auto 18px;max-width:1150px}}
h2{{margin:0}} h2 small{{font-weight:400;color:#666;font-size:13px}} h4{{margin:10px 0 4px;font-size:12px;color:#555;text-transform:uppercase;letter-spacing:.06em}}
.src{{margin:2px 0 10px;color:#555;font-size:12px}} .cols{{display:grid;grid-template-columns:320px 1fr;gap:18px}}
.grid{{display:grid;grid-template-columns:repeat(auto-fill,minmax(205px,1fr));gap:4px}}
.chip{{display:flex;align-items:center;gap:6px;font-size:12px;flex-wrap:wrap}} .sw{{width:22px;height:22px;border-radius:5px;border:1px solid #0002;flex:none}}
.chip code{{font-size:12px}} .aa{{display:flex;align-items:center;gap:4px;color:#555;font-size:11px;margin-left:6px}} .aa .sw{{width:14px;height:14px}} .chip em{{color:#888;font-style:normal;margin-left:auto}}
.pv{{border-radius:8px;padding:12px 14px}} .pv pre{{padding:8px;border-radius:6px;font-size:12px;white-space:pre-wrap}} .pv p{{margin:8px 0}}
@media (max-width:760px){{.cols{{grid-template-columns:1fr}}}}
</style></head><body><h1 style="max-width:1150px;margin:0 auto 12px">ArkMD theme sheet</h1>
<p style="max-width:1150px;margin:0 auto 16px">Every colour role per theme with its official hex value; ratios are contrast against the
page background (syntax: against the code-block background). "→" shows the WCAG AA adjustment (4.5:1) the app uses
by default; the preview shows official colours. Generated by tools/theme_sheet.py from shared/web/themes.json.</p>
{"".join(cards)}</body></html>"""
out = os.path.join(ROOT, "design", "theme-sheet.html")
open(out, "w").write(page)
print("wrote", out)
